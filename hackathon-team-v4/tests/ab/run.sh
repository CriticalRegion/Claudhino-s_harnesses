#!/usr/bin/env bash
# A/B usage test for the `lean` setting (NOT run in CI: it spends real Claude usage, ~1-2h of Sonnet).
# Builds the same small app twice, headless, with the plugin loaded from this checkout:
#   off  - lean=off (the v4.0 way)
#   lean - lean=on
# Both keep one continued session, as a person would (lean only suggests /clear once a session is big, and this app stays small).
# Then checks the result independently (build + the demo path over HTTP) and compares token usage.
# Usage: bash tests/ab/run.sh <empty work dir> [off|lean|both]   (Linux; needs claude, node, npm, git, curl)
# Runs with --permission-mode bypassPermissions, confined to the throwaway work dir.
set -u
HARN=$(cd "$(dirname "$0")/../.." && pwd); W=${1:?usage: run.sh <work dir> [off|lean|both]}; ARMS=${2:-both}
mkdir -p "$W"; W=$(cd "$W" && pwd); [ "$ARMS" = both ] && ARMS="off lean"
export XDG_CONFIG_HOME=$W/xdg HK_NO_CLAUDE_CLI=1 HK_WATCH_MAX=5 GIT_TERMINAL_PROMPT=0
export CLAUDE_CODE_EFFORT_LEVEL=${AB_EFFORT:-high}   # same effort in both arms, so only lean's other changes differ
TMO=${AB_TASK_TIMEOUT:-1800}

TASKS="t0-scaffold t1-api t2-redirect t3-ui"
card(){ case $1 in
  t0-scaffold) echo "files: (generated by create-next-app); do: npx create-next-app@latest . --ts --app --tailwind --eslint --no-src-dir --use-npm --yes, then check + smoke scripts; done: npm run check passes";;
  t1-api) echo "files: lib/store.ts, app/api/links/route.ts, app/api/links/[code]/route.ts; done: POST /api/links {url} -> {code}; GET /api/links/<code> -> {url, clicks}";;
  t2-redirect) echo "files: app/[code]/route.ts, lib/store.ts; done: GET /<code> redirects (307) to the url and counts a click";;
  t3-ui) echo "files: app/page.tsx, app/stats/[code]/page.tsx; done: the form shows the short link; /stats/<code> shows the click count";;
  esac; }
plain(){ case $1 in   # what a v4.0 kickoff/slice would have written: no file list
  t0-scaffold) echo "scaffold Next.js, check script, demo-check";;
  t1-api) echo "links API: create and read a short link";;
  t2-redirect) echo "redirect a short link and count clicks";;
  t3-ui) echo "home page form and stats page";;
  esac; }
deps(){ case $1 in t0-scaffold) echo -;; t1-api) echo t0-scaffold;; *) echo t1-api;; esac; }

setup(){ # arm -> a fresh project with the plan and board filled in
  local a=$1 d=$W/$1; rm -rf "$d" "$W/$1.git"; git init -q -b main "$d"; cd "$d" || exit 1
  HK_ROOT=$d bash "$HARN/bin/hk" install-project --mcp none --ponytail off --model sonnet >/dev/null
  node -e 'const f=".claude/settings.json",j=require("./"+f); delete j.enabledPlugins; delete j.extraKnownMarketplaces; require("fs").writeFileSync(f, JSON.stringify(j,null,2))'
  cat > .hackathon/PLAN.md <<'PLAN'
# Plan
## Event
- Name / dates: A/B test hackathon
- Deadline (local): in 6 hours
- Brief / theme: tools people use every day
- Judging criteria (weights): working demo 50, usefulness 30, polish 20
- Team (handle: skills, usage-window start): @ab: full-stack
## Plan
- One-line pitch: Shortly - paste a long URL, get a short link, see how often it's clicked.
- Demo path (3-5 steps a judge will see): 1. paste a URL on the home page and get a short link  2. open the short link: it redirects  3. /stats/<code> shows the click count
- Stack: Next.js (app router, TypeScript, Tailwind), in-memory store (lib/store.ts), no auth
- Scaffold command (official starter/generator): npx create-next-app@latest . --ts --app --tailwind --eslint --no-src-dir --use-npm --yes
- Mocked, not integrated (FAKE:): persistence (in-memory, resets on restart)
- API contract: POST /api/links {url} -> 201 {code}; GET /api/links/<code> -> {url, clicks}; GET /<code> -> 307 to url (+1 click)
- Owners (directory -> @name): everything -> @ab
- Dev command / local URL: npm run dev / http://localhost:3000
- Live URL: none (this test is local only: skip deploys)
- Milestones (clock time): [ ] M1 skeleton  [ ] M2 API  [ ] M3 redirect  [ ] M4 UI
## Cut list (not building)
- accounts, custom codes, persistence, analytics beyond a click count
PLAN
  git add -A; git commit -qm "plan"; git init -q --bare "$W/$a.git"; git remote add origin "$W/$a.git"; git push -q -u origin main
  local hk=".hackathon/bin/hk"
  bash $hk init ab >/dev/null; bash $hk discord off >/dev/null
  bash $hk config set wake=off "lean=$([ "$a" = lean ] && echo on || echo off)" >/dev/null
  for t in $TASKS; do if [ "$a" = lean ]; then r=$(card $t); else r=$(plain $t); fi
    bash $hk add "$t" "$r" --after "$(deps $t)" >/dev/null; done
  bash $hk session-start </dev/null >/dev/null   # applies (or not) the lean Claude Code settings
}

prompt(){ echo "Board task $1. /hackathon:claim $1, build it with /hackathon:slice, then /hackathon:handoff $1 <path:line>. This test is local only: no deploys, and skip demo-check steps that need a live URL (the app runs with npm run dev on port 3000). Don't ask questions; decide and continue."; }

kill_servers(){ local d=$1 p c; for p in $(pgrep -f 'next|node' 2>/dev/null); do c=$(readlink "/proc/$p/cwd" 2>/dev/null || true)
  case $c in "$d"|"$d"/*) kill "$p" 2>/dev/null;; esac; done; }

run_arm(){ local a=$1 d=$W/$1 first=1 t s; setup "$a"; : > "$W/$a.runlog"; s=$(date +%s)
  for t in $TASKS; do
    echo "== $a $t $(date +%T)" >> "$W/$a.runlog"
    if [ $first = 0 ]; then cont=--continue; else cont=; fi
    (cd "$d" && timeout "$TMO" claude -p "$(prompt $t)" $cont --model sonnet --plugin-dir "$HARN" \
       --permission-mode bypassPermissions --output-format json </dev/null >> "$W/$a.runlog" 2>&1)
    echo "   exit $?" >> "$W/$a.runlog"; first=0
  done
  echo $(( $(date +%s) - s )) > "$W/$a.secs"; kill_servers "$d"; verify "$a"; usage "$a"
}

verify(){ local a=$1 d=$W/$1 port r code loc clicks; port=$([ "$a" = lean ] && echo 3201 || echo 3202); cd "$d" || return
  r=$W/$a.result; : > "$r"
  if npm run build >/dev/null 2>&1; then echo "build PASS" >> "$r"; (npx next start -p $port >/dev/null 2>&1 &)
  else echo "build FAIL" >> "$r"; (npx next dev -p $port >/dev/null 2>&1 &); fi
  for i in $(seq 1 60); do curl -s -o /dev/null "http://localhost:$port/" && break; sleep 1; done
  code=$(curl -s -X POST -H 'content-type: application/json' -d '{"url":"https://example.com/a/very/long/path"}' "http://localhost:$port/api/links" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{console.log(JSON.parse(s).code||"")}catch(e){console.log("")}})')
  [ -n "$code" ] && echo "step1 create PASS ($code)" >> "$r" || echo "step1 create FAIL" >> "$r"
  loc=$(curl -s -o /dev/null -w '%{http_code} %{redirect_url}' "http://localhost:$port/$code")
  case $loc in 30[1278]" https://example.com/a/very/long/path") echo "step2 redirect PASS" >> "$r";; *) echo "step2 redirect FAIL ($loc)" >> "$r";; esac
  clicks=$(curl -s "http://localhost:$port/api/links/$code" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{console.log(JSON.parse(s).clicks)}catch(e){console.log("")}})')
  [ "$clicks" = 1 ] && echo "step3 clicks PASS" >> "$r" || echo "step3 clicks FAIL ($clicks)" >> "$r"
  curl -s "http://localhost:$port/stats/$code" | grep -q '1' && echo "stats page PASS" >> "$r" || echo "stats page FAIL" >> "$r"
  curl -s "http://localhost:$port/" | grep -qi '<form' && echo "home form PASS" >> "$r" || echo "home form FAIL" >> "$r"
  kill_servers "$d"
}

usage(){ local a=$1 pdir; pdir=$HOME/.claude/projects/$(printf '%s' "$W/$a" | sed 's/[^A-Za-z0-9]/-/g')
  find "$pdir" -name '*.jsonl' 2>/dev/null | xargs cat 2>/dev/null | grep '"usage"' | awk '
    function num(k,   r) { if (match($0, "\"" k "\":[0-9]+")) { r = substr($0, RSTART, RLENGTH); sub(/.*:/, "", r); return r + 0 } return 0 }
    { m = "?"; if (match($0, /"model":"[^"]*"/)) m = substr($0, RSTART + 9, RLENGTH - 10)
      id = NR; if (match($0, /"id":"msg_[^"]*"/)) id = substr($0, RSTART, RLENGTH)
      M[id] = m; I[id] = num("input_tokens"); W[id] = num("cache_creation_input_tokens"); C[id] = num("cache_read_input_tokens"); O[id] = num("output_tokens") }
    END { for (id in M) { f = 1; if (M[id] ~ /opus/) f = 5 / 3; else if (M[id] ~ /haiku/) f = 1 / 3
            i += I[id]; w += W[id]; c += C[id]; o += O[id]; n++; wt += f * (I[id] + 1.25 * W[id] + 0.1 * C[id] + 5 * O[id]) }
          printf "messages %d  output %d  input %d  cache-write %d  cache-read %d  weighted %.0f\n", n, o, i, w, c, wt }' > "$W/$a.usage"
}

for a in $ARMS; do run_arm "$a"; done
echo "A/B results ($W)"; for a in $ARMS; do echo "--- $a ($(cat "$W/$a.secs" 2>/dev/null)s)"; cat "$W/$a.usage" "$W/$a.result" 2>/dev/null; done
